#!/usr/bin/env python3
"""把同一个仓库打成两个互不依赖的产品。

    python packaging/build.py            # 两个都打
    python packaging/build.py agent1     # 只打 Agent-1
    python packaging/build.py platform   # 只打平台包

产物：

    dist/agent1-standalone/
        defect-batch-prepare/           skill（只有文档：SKILL.md + references + evals）
        defect-batch-prepare/scripts/agent1.exe    零依赖单文件 CLI
    dist/agent1-standalone.zip        交付包不含任何源码

    dist/bugfix-agent-platform.zip      平台包（根级 graph.py + 源码 + platform skills）

源码边界（打包拷整个目录，不再维护文件白名单）：

    Agent-1     contracts/bugfix_contracts + agent1/bugfix_agent1 + agent1/skills
    Platform    contracts/bugfix_contracts + platform/bugfix_platform + platform/skills

两侧都不导入对方的其余模块。共享只走 ``bugfix_contracts`` 与落盘 JSON。
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = Path(__file__).resolve().parent
DIST = ROOT / "dist"
BUILD = ROOT / "build"

AGENT1_SKILL = "defect-batch-prepare"

# SKILL.md 会引用其中的产物契约；不随包走的话 skill 装到 agent 里就是个死链。
# 单一真源仍在 docs/contracts/，构建时复制进 references/。
SKILL_BUNDLED_DOCS = {
    "references/defect-batch-guide.md": (
        ROOT / "docs" / "contracts" / "v0.1" / "defect-batch-guide.md"
    ),
    # guide 里链了产物样例；不带上就又是一处死链
    "references/samples/defect-batch.sample.json": (
        ROOT / "docs" / "contracts" / "v0.1" / "samples" / "defect-batch.sample.json"
    ),
}
_IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo")


def log(msg: str) -> None:
    print(f"[build] {msg}", flush=True)


def strip_pycache(root: Path) -> int:
    """删掉 __pycache__ / *.pyc：验证步骤会 import 暂存树，留下字节码缓存。"""
    n = 0
    for d in root.rglob("__pycache__"):
        if d.is_dir():
            shutil.rmtree(d, ignore_errors=True)
            n += 1
    for p in root.rglob("*.pyc"):
        p.unlink(missing_ok=True)
    return n


def copy_python_tree(src: Path, dest: Path) -> None:
    if not src.is_dir():
        raise SystemExit(f"missing source tree: {src}")
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(src, dest, ignore=_IGNORE)


def write_manifest(vendor: Path, label: str) -> None:
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except Exception:  # noqa: BLE001 - 不是 git 仓库也能打包
        commit = "unknown"
    files = {
        str(p.relative_to(vendor)).replace("\\", "/"): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(vendor.rglob("*.py"))
    }
    (vendor / "VENDOR.json").write_text(
        json.dumps(
            {
                "source": f"bugfix-agent ({label})",
                "repo": "bugfix-agent",
                "commit": commit,
                "copiedAt": datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"),
                "note": "generated by packaging/build.py; do not edit by hand",
                "files": files,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def build_agent1(skip_exe: bool = False) -> Path:
    """产出**只有 exe** 的 skill；源码不进交付包（单一真源在仓库里）。"""
    skill_src = ROOT / "agent1" / "skills" / AGENT1_SKILL
    stage = BUILD / "agent1-stage" / AGENT1_SKILL
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)

    log("agent1: staging build tree (not shipped)")
    shutil.copy2(skill_src / "SKILL.md", stage / "SKILL.md")
    for sub in ("references", "evals"):
        shutil.copytree(skill_src / sub, stage / sub)
    _bundle_skill_docs(stage)
    scripts = stage / "scripts"
    scripts.mkdir()
    (scripts / "entry.py").write_text(
        "\n".join([
            "import sys",
            "from bugfix_agent1.agent1 import entry",
            "sys.exit(entry())",
            "",
        ]),
        encoding="utf-8",
    )

    vendor = scripts / "_vendor"
    copy_python_tree(ROOT / "contracts" / "bugfix_contracts", vendor / "bugfix_contracts")
    copy_python_tree(ROOT / "agent1" / "bugfix_agent1", vendor / "bugfix_agent1")
    write_manifest(vendor, "Agent-1: bugfix_contracts + bugfix_agent1")
    n_py = len(list(vendor.rglob("*.py")))
    log(f"agent1: vendored {n_py} python files for the build")

    exe_name = "agent1.exe" if os.name == "nt" else "agent1"
    if skip_exe:
        if not (scripts / exe_name).exists():
            raise SystemExit("agent1: --skip-exe but the staging tree has no prebuilt exe")
    else:
        log("agent1: running PyInstaller (30-60s)")
        stamp = BUILD / "pyinstaller"
        env = dict(os.environ, PYTHONPATH=str(vendor))
        excludes: list[str] = []
        for mod in (
            "setuptools", "pkg_resources", "packaging",
            "pydoc_data", "ssl", "_ssl", "_hashlib",
            "asyncio", "tkinter", "unittest", "lib2to3", "distutils", "xmlrpc",
            "langgraph", "bugfix_platform",
        ):
            excludes += ["--exclude-module", mod]
        subprocess.run(
            [
                sys.executable, "-m", "PyInstaller", "--onefile", "--name", "agent1",
                "--noconfirm", "--clean",
                "--add-data", f"{vendor / 'VENDOR.json'}{os.pathsep}.",
                "--hidden-import", "openpyxl",
                "--hidden-import", "bugfix_contracts",
                "--hidden-import", "bugfix_agent1",
                *excludes,
                "--distpath", str(stamp / "dist"),
                "--workpath", str(stamp / "work"),
                "--specpath", str(stamp),
                str(scripts / "entry.py"),
            ],
            cwd=scripts, env=env, check=True,
            stdout=subprocess.DEVNULL, stderr=subprocess.STDOUT,
        )
        built = stamp / "dist" / exe_name
        shutil.copy2(built, scripts / exe_name)
        log(f"agent1: {exe_name} {(scripts / exe_name).stat().st_size / 1e6:.1f} MB")

    _verify_agent1(scripts)

    log("agent1: assembling exe-only package")
    out = BUILD / "agent1-standalone" / AGENT1_SKILL
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    shutil.copy2(stage / "SKILL.md", out / "SKILL.md")
    for sub in ("references", "evals"):
        shutil.copytree(stage / sub, out / sub)
    (out / "scripts").mkdir()
    shutil.copy2(scripts / exe_name, out / "scripts" / exe_name)
    shutil.copy2(PKG / "agent1" / "README.md", out.parent / "README.md")

    strip_pycache(out.parent)
    _verify_skill_docs(out)
    _verify_package(out)

    zip_path = DIST / "agent1-standalone.zip"
    zip_tree(out.parent, zip_path)
    log(f"agent1: -> {zip_path.name} {zip_path.stat().st_size / 1e6:.1f} MB")
    return zip_path


def _bundle_skill_docs(stage: Path) -> None:
    """把契约文档/样例复制进 skill（源仍在 docs/contracts/）。"""
    for rel, src in SKILL_BUNDLED_DOCS.items():
        if not src.is_file():
            raise SystemExit(f"agent1: bundled doc missing in repo: {src}")
        dst = stage / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        log(f"agent1: bundled {rel} ({src.stat().st_size} B)")


_MD_LINK = re.compile(r"\]\(([^)#?]+)\)")


def _verify_skill_docs(stage: Path) -> None:
    """skill 装到 agent 里必须自洽：相对链接都得指到包内真文件。"""
    problems: list[str] = []
    skill = stage / "SKILL.md"
    if not skill.is_file():
        raise SystemExit("agent1: SKILL.md missing in stage")
    for md in [skill, *sorted((stage / "references").glob("*.md"))]:
        text = md.read_text(encoding="utf-8")
        for rel in _MD_LINK.findall(text):
            if rel.startswith(("http://", "https://", "#", "mailto:")):
                continue
            target = (md.parent / rel).resolve()
            if not target.is_file():
                problems.append(f"{md.relative_to(stage)} -> {rel}")
        # 反引号里的 repo 路径在包里不存在；同一行必须标 "repo" 才允许出现
        for lineno, line in enumerate(text.splitlines(), 1):
            for raw in re.findall(r"`(docs/[^`]+)`", line):
                if (ROOT / raw).exists() and "repo" not in line.lower():
                    problems.append(
                        f"{md.relative_to(stage)}:{lineno} cites repo path {raw!r} unmarked"
                    )
    if problems:
        joined = "\n  ".join(problems)
        raise SystemExit(f"agent1: skill docs are not self-contained:\n  {joined}")
    log("agent1: skill docs self-contained (all relative links resolve)")


def _verify_agent1(scripts: Path) -> None:
    """确认裁剪后的源码树能独立导入（不碰平台包）。"""
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    vendor = scripts / "_vendor"
    if (vendor / "bugfix_platform").exists():
        raise SystemExit("agent1: platform tree leaked into vendor")
    if (vendor / "bugfix_agent1" / "workflow").exists():
        raise SystemExit("agent1: workflow leaked into vendor")
    code = (
        "import sys; sys.path.insert(0, r'%s');"
        "from bugfix_agent1.defect_batch import run_defect_batch_prepare;"
        "import bugfix_agent1;"
        "assert not hasattr(bugfix_agent1, 'run_three_agent_workflow'), 'platform leaked into agent1 build';"
        "assert 'langgraph' not in sys.modules, 'agent1 build pulled langgraph';"
        "print('  ok: agent1 imports clean, no langgraph')"
    ) % vendor
    subprocess.run([sys.executable, "-B", "-c", code], check=True, cwd=ROOT, env=env)
    exe = scripts / ("agent1.exe" if os.name == "nt" else "agent1")
    if exe.exists():
        subprocess.run([str(exe), "self-check"], check=True)


def _verify_package(out: Path) -> None:
    """交付包必须只有 exe，且 exe 能在没有源码的目录里对着真实夹具跑完 Step 1。"""
    log("agent1: verifying exe-only package")
    survivors = [p for p in out.rglob("*") if p.is_file()]
    leaked = [
        p for p in survivors
        if p.suffix in (".py", ".pyc") or p.name == "requirements.txt"
    ]
    if leaked:
        raise SystemExit(f"source leaked into the shipped package: {[str(p) for p in leaked]}")
    if not (out / "SKILL.md").is_file():
        raise SystemExit("shipped package is missing SKILL.md")

    exe = out / "scripts" / ("agent1.exe" if os.name == "nt" else "agent1")
    fixture = ROOT / "test" / "fixtures" / "defect-batch" / "hc1-raw.json"
    if not fixture.is_file():
        raise SystemExit(f"missing smoke fixture: {fixture}")
    smoke = BUILD / "smoke"
    smoke.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            str(exe), "prepare-batch", "--product-line", "smoke",
            "--source", str(fixture), "--out", str(smoke / "batch.json"),
        ],
        check=True, cwd=out, stdout=subprocess.DEVNULL,
    )
    data = json.loads((smoke / "batch.json").read_text(encoding="utf-8"))
    if not data.get("tickets"):
        raise SystemExit("shipped exe produced an empty batch")
    log(f"  ok: {len(survivors)} files, exe made {len(data['tickets'])} tickets from a real fixture")


def build_platform() -> Path:
    log("platform: staging")
    out = BUILD / "platform"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    copy_python_tree(ROOT / "contracts" / "bugfix_contracts", out / "bugfix_contracts")
    copy_python_tree(ROOT / "platform" / "bugfix_platform", out / "bugfix_platform")
    # 平台 zip 走 LangGraph Server，不带 CLI / HTTP 壳。
    (out / "bugfix_platform" / "cli.py").unlink(missing_ok=True)
    http = out / "bugfix_platform" / "http"
    if http.is_dir():
        shutil.rmtree(http)

    skills_src = ROOT / "platform" / "skills"
    shutil.copytree(skills_src, out / "skills", ignore=_IGNORE)
    if (out / "skills" / AGENT1_SKILL).exists():
        raise SystemExit("platform: Agent-1 skill leaked into platform skills")
    if (out / "bugfix_agent1").exists():
        raise SystemExit("platform: bugfix_agent1 leaked into platform zip")

    n_skills = sum(1 for p in (out / "skills").iterdir() if p.is_dir() and (p / "SKILL.md").is_file())
    log(f"platform: {n_skills} skills")

    for name in ("graph.py", "langgraph.json", "requirements.txt"):
        shutil.copy2(PKG / "platform" / name, out / name)
    shutil.copy2(ROOT / ".env.example", out / ".env.example")
    shutil.copy2(PKG / "platform" / "README.md", out / "README.md")
    (out / ".env").write_text("# 平台复用「模型管理」，这里留空即可。\n", encoding="utf-8")

    log("platform: verifying graph builds from the staged tree alone")
    _verify_platform(out)
    strip_pycache(out)

    zip_path = DIST / "bugfix-agent-platform.zip"
    zip_tree(out, zip_path)
    log(f"platform: -> {zip_path.name} {zip_path.stat().st_size / 1024:.0f} KB")
    return zip_path


def _verify_platform(staging: Path) -> None:
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    code = (
        "import sys; sys.path.insert(0, r'%s');"
        "from graph import graph, build_graph;"
        "assert build_graph() is graph, 'build_graph() must return the same compiled graph';"
        "assert hasattr(graph, 'invoke'), 'graph is not compiled (missing invoke)';"
        "nodes = set(graph.get_graph().nodes);"
        "assert {'agent2', 'agent3'} <= nodes, f'unexpected nodes: {sorted(nodes)}';"
        "assert 'agent1' not in nodes, 'agent1 must stay outside the graph';"
        "import bugfix_platform;"
        "assert 'bugfix_agent1' not in sys.modules, 'agent1 leaked into platform build';"
        "print('  ok: graph builds, nodes =', sorted(nodes))"
    ) % staging
    subprocess.run([sys.executable, "-B", "-c", code], check=True, cwd=ROOT, env=env)


def sync_delivery(target_root: Path) -> None:
    """把仓库里构建好的 skill 同步到交付目录。

    唯一真源始终是仓库：改代码、改文档都在 ``agent1/`` 里做，然后跑一次
    build 同步出去。目标目录只被本函数写，不要手改。
    """
    out_root = BUILD / "agent1-standalone"
    if not (out_root / AGENT1_SKILL).is_dir():
        raise SystemExit("sync: run `build.py agent1` first; no staging tree found")

    log(f"sync: -> {target_root}")
    target_root.mkdir(parents=True, exist_ok=True)
    for name in (AGENT1_SKILL, "README.md"):
        dst = target_root / name
        if dst.is_dir():
            shutil.rmtree(dst)
        elif dst.exists():
            dst.unlink()
        src = out_root / name
        if src.is_dir():
            shutil.copytree(src, dst)
        else:
            shutil.copy2(src, dst)
    strip_pycache(target_root)
    _write_skill_zip(out_root, target_root / f"{AGENT1_SKILL}.zip")
    _verify_delivery(out_root, target_root)


def _write_skill_zip(out_root: Path, zip_path: Path) -> None:
    """重生成 skill-only zip。

    交付目录里那份 zip 是直接上传给 agent 平台的安装体；不随目录一起刷新
    的话，它会停在旧 exe + 旧 SKILL.md（实际就发生过）。
    """
    if zip_path.exists():
        zip_path.unlink()
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        skill = out_root / AGENT1_SKILL
        for path in sorted(skill.rglob("*")):
            if path.is_file():
                zf.write(path, path.relative_to(out_root).as_posix())
    log(f"sync: refreshed {zip_path.name} ({zip_path.stat().st_size / 1e6:.1f} MB)")


def _verify_delivery(out_root: Path, target_root: Path) -> None:
    """交付目录必须与 build 产物逐字节一致，且不留源码。"""
    def digest(root: Path, names: tuple[str, ...]) -> dict[str, str]:
        out: dict[str, str] = {}
        for name in names:
            base = root / name
            paths = [base] if base.is_file() else sorted(p for p in base.rglob("*") if p.is_file())
            for f in paths:
                out[str(f.relative_to(root)).replace("\\", "/")] = hashlib.sha256(f.read_bytes()).hexdigest()
        return out

    names = (AGENT1_SKILL, "README.md")
    want, got = digest(out_root, names), digest(target_root, names)
    if want != got:
        only_build = sorted(set(want) - set(got))
        only_deliv = sorted(set(got) - set(want))
        diff = sorted(k for k in set(want) & set(got) if want[k] != got[k])
        raise SystemExit(
            "sync: delivery does not match the build -- "
            f"missing={only_build} extra={only_deliv} differing={diff}"
        )
    leaked = [k for k in got if k.endswith((".py", ".pyc"))]
    if leaked:
        raise SystemExit(f"sync: source leaked into delivery: {leaked}")
    log(f"  ok: {len(got)} files match the build byte-for-byte")


def zip_tree(src: Path, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted(src.rglob("*")):
            if p.is_file() and "__pycache__" not in p.parts:
                z.write(p, p.relative_to(src).as_posix())
                n += 1
    log(f"  zipped {n} files")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("target", nargs="?", choices=["all", "agent1", "platform"], default="all")
    ap.add_argument("--skip-exe", action="store_true", help="agent1: 只组装脚本，不跑 PyInstaller")
    ap.add_argument(
        "--deliver-to",
        type=Path,
        default=None,
        help="agent1: 构建后把 skill 同步到该交付目录（唯一真源仍是仓库）",
    )
    args = ap.parse_args(argv)

    DIST.mkdir(exist_ok=True)
    if args.target in ("all", "agent1"):
        build_agent1(skip_exe=args.skip_exe)
        if args.deliver_to is not None:
            sync_delivery(args.deliver_to)
    if args.target in ("all", "platform"):
        build_platform()
    log("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
